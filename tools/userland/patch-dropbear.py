#!/usr/bin/env python3
"""Patch a dropbear 2022.83 tree for the picasso port.

    patch-dropbear.py SRC_DIR HOSTKEY_FILE AUTHORIZED_KEYS_FILE

The port's VFS cannot create files reliably (O_CREAT/fsync/link wedge the HFS+
write path), and account lookups go to opendirectoryd, which does not run. So
this build of dropbear needs neither:

  * single-user build (DROPBEAR_SVR_MULTIUSER 0, DROPBEAR_DO_REEXEC 0): no
    setuid/initgroups/fexecve per session; the "requires a non-multiuser kernel"
    getuid() check is skipped, like ios-flame's IOSONPIXEL_SINGLE_ROOT;
  * no pidfile creation on startup (fopen("/var/run/dropbear.pid", "w") is an
    O_CREAT on HFS+ right before the accept loop);
  * pty_setowner() is a no-op (single-root system; devfs chown/chmod failures
    would otherwise abort the session);
  * account lookups are synthesized (picasso_pw.h), never sent to the daemon;
  * an ed25519 host key is compiled in and used when no key file can be read,
    so -R / dropbearkey (which create files) are never needed;
  * one authorized key is compiled in and checked whenever
    ~/.ssh/authorized_keys is absent, has wrong permissions, or does not match.

The host key is generated per build (CI, with a host-built dropbearkey) and is
never committed. Every edit asserts its anchor, so a different dropbear version
fails loudly instead of building something half-patched.
"""
import pathlib
import sys


def edit(path, old, new, count=1):
    text = path.read_text()
    n = text.count(old)
    if n != count:
        sys.exit("%s: expected %d anchor(s), found %d:\n%s" % (path.name, count, n, old))
    path.write_text(text.replace(old, new))


def c_array(name, data):
    body = ",".join("0x%02x" % b for b in data)
    return "static const unsigned char %s[] = {%s};\nstatic const unsigned int %s_len = %d;\n" % (
        name, body, name, len(data))


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    src = pathlib.Path(sys.argv[1])
    hostkey = pathlib.Path(sys.argv[2]).read_bytes()
    authkey = pathlib.Path(sys.argv[3]).read_text().strip().splitlines()[0].strip()
    if not authkey.startswith(("ssh-ed25519 ", "ssh-rsa ", "ecdsa-")):
        sys.exit("authorized key does not look like an OpenSSH public key")

    here = pathlib.Path(__file__).resolve().parent
    (src / "picasso_pw.h").write_text((here / "picasso_pw.h").read_text())
    (src / "picasso_keys.h").write_text(
        "/* generated by patch-dropbear.py - do not commit */\n" +
        c_array("picasso_hostkey", hostkey) +
        "static const char picasso_authkey[] = \"%s\";\n" % authkey.replace("\\", "\\\\").replace('"', '\\"'))
    (src / "localoptions.h").write_text(
        "/* picasso port: single root, public key only, no files created */\n"
        "#define DROPBEAR_SVR_MULTIUSER 0\n"
        "#define DROPBEAR_REEXEC 0\n"
        "#define DROPBEAR_SVR_PASSWORD_AUTH 0\n"
        "#define DROPBEAR_SVR_PAM_AUTH 0\n"
        "#define PICASSO_SINGLE_ROOT 1\n"
        "#define RSA_PRIV_FILENAME \"/private/var/root/dropbear_rsa_host_key\"\n"
        "#define DSS_PRIV_FILENAME \"/private/var/root/dropbear_dss_host_key\"\n"
        "#define ECDSA_PRIV_FILENAME \"/private/var/root/dropbear_ecdsa_host_key\"\n"
        "#define ED25519_PRIV_FILENAME \"/private/var/root/dropbear_ed25519_host_key\"\n"
        "#define DEFAULT_PATH \"/private/var/root:/usr/bin:/bin:/usr/sbin:/sbin\"\n")

    for name in ("common-session.c", "svr-chansession.c", "loginrec.c", "svr-auth.c",
                 "svr-authpubkey.c", "dbutil.c", "dropbearkey.c", "sshpty.c", "svr-runopts.c"):
        p = src / name
        p.write_text('#include "picasso_pw.h"\n' + p.read_text())

    # 1. single root: the kernel has getuid(), which is fine here.
    edit(src / "common-session.c",
         "#if !DROPBEAR_SVR_MULTIUSER\n\t/* A sanity check",
         "#if !DROPBEAR_SVR_MULTIUSER && !PICASSO_SINGLE_ROOT\n\t/* A sanity check")

    # 1b. accept /private/var/root/sh without consulting /etc/shells (getusershell()
    # only returns /bin/sh and /bin/csh, so checkusername() rejected every login).
    edit(src / "svr-auth.c",
         "\t/* check the shell is valid.",
         "\t(void)listshell; (void)usershell; goto goodshell;\n\t/* check the shell is valid.")

    # 2. do not touch the filesystem to write /var/run/dropbear.pid before select().
    edit(src / "svr-main.c",
         "\t/* create a PID file so that we can be killed easily */\n"
         "\tpidfile = fopen(svr_opts.pidfile, \"w\");\n"
         "\tif (pidfile) {\n"
         "\t\tfprintf(pidfile, \"%d\\n\", getpid());\n"
         "\t\tfclose(pidfile);\n"
         "\t}\n",
         "\t(void)pidfile; /* picasso: no pidfile write on HFS+ */\n")

    # 3. single root: do not abort if chown/chmod on a pty node fails.
    edit(src / "sshpty.c",
         "void\npty_setowner(struct passwd *pw, const char *tty_name)\n{",
         "void\npty_setowner(struct passwd *pw, const char *tty_name)\n{\n"
         "#if PICASSO_SINGLE_ROOT\n\t(void)pw; (void)tty_name; return;\n#endif")

    # 4. compiled-in host key when no file provides one.
    edit(src / "svr-runopts.c",
         "void load_all_hostkeys() {",
         "#include \"picasso_keys.h\"\n"
         "static void picasso_load_builtin_hostkey(void) {\n"
         "\tbuffer *buf;\n"
         "\tenum signkey_type type = DROPBEAR_SIGNKEY_ANY;\n"
         "\tsign_key *key;\n"
         "#if DROPBEAR_ED25519\n"
         "\tif (svr_opts.hostkey->ed25519key) {\n"
         "\t\treturn;\n"
         "\t}\n"
         "#endif\n"
         "\tbuf = buf_new(picasso_hostkey_len);\n"
         "\tbuf_putbytes(buf, picasso_hostkey, picasso_hostkey_len);\n"
         "\tbuf_setpos(buf, 0);\n"
         "\tkey = new_sign_key();\n"
         "\tif (buf_get_priv_key(buf, key, &type) == DROPBEAR_SUCCESS) {\n"
         "\t\tloadhostkey_helper(\"built-in\", (void**)&key->ed25519key,\n"
         "\t\t\t(void**)&svr_opts.hostkey->ed25519key, 0);\n"
         "\t\tdropbear_log(LOG_INFO, \"Using the built-in ed25519 host key\");\n"
         "\t} else {\n"
         "\t\tdropbear_log(LOG_WARNING, \"Built-in host key did not parse\");\n"
         "\t}\n"
         "\tsign_key_free(key);\n"
         "\tbuf_burn_free(buf);\n"
         "}\n\n"
         "void load_all_hostkeys() {")
    edit(src / "svr-runopts.c",
         "#if DROPBEAR_ED25519\n\t\tloadhostkey(ED25519_PRIV_FILENAME, 0);\n#endif\n\t}\n",
         "#if DROPBEAR_ED25519\n\t\tloadhostkey(ED25519_PRIV_FILENAME, 0);\n#endif\n\t}\n"
         "\tpicasso_load_builtin_hostkey();\n")

    # 5. compiled-in authorized key fallback whenever file-based check did not succeed.
    edit(src / "svr-authpubkey.c",
         "out:\n\tif (authfile) {",
         "out:\n"
         "\tif (ret != DROPBEAR_SUCCESS) {\n"
         "#include \"picasso_keys.h\"\n"
         "\t\tbuffer *bline = buf_new(MAX_AUTHKEYS_LINE);\n"
         "\t\tbuf_putbytes(bline, (const unsigned char *)picasso_authkey, strlen(picasso_authkey));\n"
         "\t\tbuf_setpos(bline, 0);\n"
         "\t\tret = checkpubkey_line(bline, 1, \"built-in\", keyalgo, keyalgolen,\n"
         "\t\t\tkeyblob, keybloblen, &ses.authstate.pubkey_info);\n"
         "\t\tbuf_free(bline);\n"
         "\t}\n"
         "\tif (authfile) {")
    print("dropbear patched for picasso (%d-byte host key, key %s...)" % (len(hostkey), authkey[:24]))


if __name__ == "__main__":
    main()
